#!/usr/bin/env node
/* Pack the toy LBM results (sim/out/<case>.bin + .json) into ../field.js for the reel page.
 * u, v (normalised by mean inlet speed) and p (normalised by rho*Um^2) are quantised to Int16, cropped to YMAX mm. */
const fs = require('fs');
const path = require('path');
const OUT = path.join(__dirname, process.argv[2] || '_scratch/out900');
const FALLBACK = path.join(__dirname, '_scratch/out');
const CASES = ['open3', 'side3']; // side1 (needle 1 mm short) was dropped from the reel after review: the 2-D toy is not shown for that case
const YMAX = 6.9; // mm kept (display shows up to ~6.4 mm)
const res = {};
for (const c of CASES) {
  const dir = fs.existsSync(path.join(OUT, c + '.json')) ? OUT : FALLBACK;
  if (dir !== OUT) console.log('  (fallback for', c, ')');
  const meta = JSON.parse(fs.readFileSync(path.join(dir, c + '.json'), 'utf8'));
  const raw = fs.readFileSync(path.join(dir, c + '.bin'));
  const { nx, ny, dx } = meta; const N = nx * ny;
  const rows = Math.min(ny, Math.ceil(YMAX / dx) + 2);
  const M = nx * rows;
  const q = new Int16Array(3 * M); const mask = new Uint8Array(M);
  const S_UV = 8000, S_P = 1000;
  for (let n = 0; n < M; n++) {
    const u = raw.readFloatLE(n * 4), v = raw.readFloatLE((N + n) * 4), p = raw.readFloatLE((2 * N + n) * 4);
    q[n] = Math.max(-32767, Math.min(32767, Math.round(u * S_UV)));
    q[M + n] = Math.max(-32767, Math.min(32767, Math.round(v * S_UV)));
    q[2 * M + n] = Math.max(-32767, Math.min(32767, Math.round(p * S_P)));
    mask[n] = raw[12 * N + n];
  }
  res[c] = { ...meta, rows, sUV: S_UV, sP: S_P, q: Buffer.from(q.buffer).toString('base64'), mask: Buffer.from(mask).toString('base64') };
  console.log(c, 'rows', rows, 'apicalP', meta.apicalP.toFixed(3));
}
const js = '/* generated by sim/export.cjs — toy 2-D LBM fields (schematic), do not edit */\nwindow.FIELDS = ' + JSON.stringify(res) + ';\n';
fs.writeFileSync(path.join(__dirname, '..', 'field.js'), js);
console.log('field.js', (js.length / 1024).toFixed(0), 'KB');
